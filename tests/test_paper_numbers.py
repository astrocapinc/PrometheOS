def test_no_manuscript_and_agent_visibility(env: Env) -> None:
    files = _all(env)
    pid = new_id("paper")
    env.apply([create("paper", paper_body(), pid)])
    got = env.svc.paper_numbers(env.project_id, AGENT, pid)
    assert got["manuscript"] is None and got["counts"] == {}
    # A paper on a restricted manuscript is restricted too: an agent cannot read it at all.
    hidden = imported_restricted(env)
    pid2 = new_id("paper")
