def test_r2_f2_f3_table_rows_in_a_macros_file_and_parameter_macros(tmp_path: Path) -> None:
    defs = [r"\newcommand{\M" + chr(65 + i) + "}{" + f"{i}.5" + "}" for i in range(9)]
