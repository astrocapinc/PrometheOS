def _doc(body: str, pre: str = "") -> str:
    return "\\documentclass{article}\n" + pre + "\\begin{document}\n" + body + "\\end{document}\n"


def _one(tmp: Path, files: dict[str, str | bytes], caller: Any = OWNER) -> dict[str, Any]:
    """A paper on ``p.tex`` with every given file imported (normal sensitivity)."""
    tmp.mkdir(parents=True, exist_ok=True)
    e = Env(tmp)
    for rel, content in files.items():
        p = e.research / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            p.write_bytes(content)
        else:
            p.write_text(content, "utf-8")
    items = imported(e, list(files))
    result: dict[str, Any] = e.svc.paper_numbers(e.project_id, caller, _paper(e, items["p.tex"]))
    return result


def test_r1_a_hand_written_macro_is_typed_by_hand(tmp_path: Path) -> None:
    got = _one(
        tmp_path / "a",
        {"p.tex": _doc(r"Peak \Peak~kJ." + "\n", r"\newcommand{\Peak}{425}" + "\n")},
    )
    assert (got["counts"]["hand_macro"], got["counts"]["macro"]) == (1, 0)
    assert got["counts"]["traced_file_only"] == 0
    assert "1 typed by hand (1 through a hand-written macro)" in got["headline"]
    # A hand-written definitions file is not a generated one, and its values are not prose.
    got = _one(
        tmp_path / "b",
        {
            "p.tex": _doc(r"\input{defs}" + "\nValue " + r"\Va." + "\n"),
            "defs.tex": r"\newcommand{\Va}{3.5}" + "\n" + r"\newcommand{\Vb}{4.5}" + "\n",
        },
    )
    c = got["counts"]
    assert (c["hand_macro"], c["typed"], c["macro"], c["checked"]) == (1, 0, 0, 1)
    assert got["macros"][0]["trace"] == "hand" and got["macro_files"] == []


