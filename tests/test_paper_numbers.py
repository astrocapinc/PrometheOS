def test_every_number_is_sorted_and_macros_trace_to_their_run(env: Env) -> None:
    files = _all(env)
    receipt(
        env,
        [files["make_report_data.m"], files["campaign.mat"]],
        [files["report/generated/macros.tex"], files["report/generated/tab_x.tex"]],
    )
    willis = line_ev(files["willis.csv"], 1)
    claimed = _claim(
        env,
        [willis],
        quantities=[
            {"decimal": "425", "unit": "kJ", "source_ref": willis, "source_pointer": "text:1:14:20"}
        ],
    )
    quoting = _claim(env, [line_ev(files["report/generated/macros.tex"], 2)])
    pid = _paper(env, files["report/paper.tex"])

    got = _numbers(env, pid)

    c = got["counts"]
    # \BenFthree, \BenBrakeOnly and \AuxN; \ArmKgWinner is text; \Unused is never used.
    assert (c["macro"], c["text_macro"]) == (3, 1)
    # 0.89, 15 and 200{,}000 here, 12.5 in the included file.
    assert c["claimed"] == 1 and c["typed"] == 4
    # Section 2, Fig. 3, Table 1, 0--100 (twice), the 5th, \S7, Phase 4--5 (twice), Model 3;
    # kWh/100 is a unit.
    assert (c["reference"], c["unit"], c["year"]) == (10, 1, 1)
    assert c["formula"] == 4  # 1, 2 and 2 in the equation; 4 inline (x_3 is a name)
    assert c["generated"] == 2  # the generated table, its mathematics included
    assert c["checked"] == 10 and c["traced_run"] == 5
    typed = {(n["path"], n["text"]) for n in got["numbers"] if n["kind"] == "typed"}
    assert typed == {
        ("report/paper.tex", "0.89"),
        ("report/paper.tex", "15"),
        ("report/paper.tex", "200,000"),
        ("report/sections/extra.tex", "12.5"),
    }
    [hit] = [n for n in got["numbers"] if n["kind"] == "claimed"]
    assert hit["claim_id"] == claimed and hit["claim_status"] == "unverified"
    assert "999" not in json.dumps(got["numbers"]) and "555" not in json.dumps(got["numbers"])
    macros = {m["name"]: m for m in got["macros"]}
    assert set(macros) == {"BenFthree", "BenBrakeOnly", "AuxN"}
    assert macros["BenFthree"]["trace"] == "run"
    assert macros["BenFthree"]["defined_at"]["line"] == 2
    assert macros["BenFthree"]["claims"] == [{"claim_id": quoting, "status": "unverified"}]
    assert macros["BenBrakeOnly"]["value"] == "-8.5"
    mf, table = got["macro_files"]
    assert mf["path"] == "report/generated/macros.tex" and (mf["defined"], mf["used"]) == (5, 4)
    assert mf["runs"][0]["inputs_changed"] == [] and mf["trace"] == "run"
    assert (table["role"], table["trace"]) == ("generated", "run")
    assert got["inputs_not_recorded"] == []
    assert got["headline"] == (
        "5 of 10 numbers traced to a recorded run; 1 match a claim's bound quantity; "
        "4 typed by hand."
    )


