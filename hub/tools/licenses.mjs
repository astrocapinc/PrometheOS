// Generate LICENSES.md from the installed node_modules package.json files, using
// package-lock.json to tell runtime from development-only and direct from transitive.
// Usage: node tools/licenses.mjs   (after `npm ci`)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const lock = JSON.parse(readFileSync(join(ROOT, "package-lock.json"), "utf-8"));
const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf-8"));
const direct = new Set([...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.devDependencies ?? {})]);

function licenseOf(meta) {
  if (typeof meta.license === "string") return meta.license;
  if (meta.license && typeof meta.license === "object" && meta.license.type) return meta.license.type;
  if (Array.isArray(meta.licenses)) return meta.licenses.map((l) => l.type ?? l).join(" OR ");
  return "UNKNOWN";
}

const rows = [];
for (const [path, entry] of Object.entries(lock.packages ?? {})) {
  if (!path) continue; // the root project
  const manifest = join(ROOT, path, "package.json");
  if (!existsSync(manifest)) continue; // optional platform package not installed here
  const meta = JSON.parse(readFileSync(manifest, "utf-8"));
  const name = meta.name ?? path.replace(/^.*node_modules\//, "");
  rows.push({
    name,
    version: meta.version ?? entry.version ?? "?",
    license: licenseOf(meta),
    scope: entry.dev ? "dev" : "runtime",
    relation: direct.has(name) && path === `node_modules/${name}` ? "direct" : "transitive",
  });
}
rows.sort((a, b) =>
  a.relation === b.relation ? a.name.localeCompare(b.name) : a.relation === "direct" ? -1 : 1,
);

const counts = {};
for (const r of rows) counts[r.license] = (counts[r.license] ?? 0) + 1;

const lines = [
  "# Dependency licences",
  "",
  "Generated by `node tools/licenses.mjs` from the `package.json` of every installed package",
  "listed in `package-lock.json`. Do not edit by hand; regenerate after changing dependencies.",
  "",
  "Only `runtime` packages are bundled into `dist/`: react, react-dom and scheduler; the",
  "CP9 LaTeX workspace adds CodeMirror 6 (@codemirror/*, @lezer/*, style-mod, crelt,",
  "@marijn/find-cluster-break) and PDF.js (pdfjs-dist, including its worker). pdfjs-dist's",
  "optional Node-only dependency @napi-rs/canvas is installed but never bundled (the browser",
  "build maps `canvas` to false). `dev` packages are build and test tools and are not shipped.",
  "",
  `Summary: ${Object.entries(counts)
    .sort()
    .map(([l, n]) => `${l} (${n})`)
    .join(", ")}.`,
  "",
  "| Package | Version | Licence | Scope | Relation |",
  "|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.scope} | ${r.relation} |`),
  "",
];
writeFileSync(join(ROOT, "LICENSES.md"), lines.join("\n"));
console.log(`LICENSES.md: ${rows.length} packages; ${JSON.stringify(counts)}`);
const unknown = rows.filter((r) => r.license === "UNKNOWN");
if (unknown.length) {
  console.error(`Unknown licences: ${unknown.map((r) => r.name).join(", ")}`);
  process.exitCode = 1;
}
